def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', default=os.path.join(ROOT, 'data'))
    ap.add_argument('--out', default=os.path.join(ROOT, 'data'))
    args = ap.parse_args()
    with open(os.path.join(args.src, 'tmaps.json'), encoding='utf-8') as f:
        tm = json.load(f)
    sigs = OrderedDict()  # sig -> {'icon': set, 'tmaps': n}
    for name in ('wd', 'sa', 'su'):
        fp = os.path.join(args.src, f'trains_{name}.json')
        if not os.path.exists(fp):
            continue
        with open(fp, encoding='utf-8') as f:
            d = json.load(f)
        T = d.get('T', []) if isinstance(d, dict) else d
        for rec in T:
            icon = rec.get('i') or ''
            if icon not in TOKKYU_ICONS and icon not in SH:
                continue
            tinfo = tm.get(str(rec.get('t')))
            if not tinfo or not tinfo.get('s_jas') or not tinfo.get('lines'):
                continue
            jas = tinfo['s_jas']
            o = norm(jas[0])
            d2 = norm(jas[-1])
            if not o or not d2:
                continue
            ls = sorted({norm(x) for x in tinfo['lines']})
            if not ls:
                continue
            sig = o + '>' + d2 + '|' + '|'.join(ls)
            e = sigs.setdefault(sig, {'icon': set(), 'tmaps': 0})
            e['icon'].add(icon)
            e['tmaps'] += 1
    print(f'unique sigs: {len(sigs)} (from trains_wd/sa/su)')

    NAMES = {}
    NAMES_I = {}  # sig|icon -> name（同一签名多个爱称时按 icon 区分）
    for o, d, fs, name, icon in P:
        ls = '|'.join(sorted(norm(x) for x in fs))
        sig = norm(o) + '>' + norm(d) + '|' + ls
        if icon:
            for ic in icon:
                NAMES_I[sig + '|' + ic] = name
        else:
            NAMES[sig] = name

    nm = {}
    nmI = {}
    left = []
    for sig, e in sigs.items():
        icons = e['icon']
        # 1) 权威名（覆盖整条签名，混跑亦适用：ラピート/京成快速特急/アクセス特急 等）
        if sig in NAMES:
            nm[sig] = NAMES[sig]
            continue
        # 2) icon 限定名（同一签名按 icon 区分：スカイライナー vs アクセス特急 / ミュースカイ vs 名鉄特急）
        if len(icons) > 1 or any(NAMES_I.get(sig + '|' + ic) for ic in icons):
            got_i = {ic: NAMES_I.get(sig + '|' + ic) for ic in icons}
            if any(v is not None for v in got_i.values()):
                for ic, v in got_i.items():
                    if v:
                        nmI[sig + '|' + ic] = v
                continue
        # 3) 神戸/阪神/阪急/山陽 系
        lsj = sig.split('|', 1)[1]
        got = kobe_rule(lsj)
        if not got:
            for sub, lab in GEN_RULES:
                if sub in lsj:
                    got = lab
                    break
        if got:
            nm[sig] = got
        else:
            left.append((sig, e))

    out = {'sh': SH, 'nm': nm, 'nmI': nmI}
